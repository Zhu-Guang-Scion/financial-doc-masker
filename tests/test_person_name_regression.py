TOTAL_CASES = len(SHOULD_MASK) + len(FORCED_CASES) + len(SHOULD_NOT_MASK)


def run() -> bool:
    engine = RuleEngine(MaskOptions(mask_person=True, person_loose=True))
    failed = []

    print(f"应脱敏组：{len(SHOULD_MASK)} 条")
    for text, expected in SHOULD_MASK:
        got = apply_replacements(text, engine.find_spans(text))
        if got == expected:
            print(f"  PASS {text} -> {got}")
        else:
            failed.append((text, expected, got))
            print(f"  FAIL {text}\n      期望: {expected}\n      实际: {got}")

    print(f"Excel 表头强制组：{len(FORCED_CASES)} 条")
    for text, expected in FORCED_CASES:
        got = apply_replacements(text, engine.find_spans(text, force_person=True))
        if got == expected:
            print(f"  PASS {text} -> {got}")
        else:
            failed.append((text, expected, got))
            print(f"  FAIL {text}\n      期望: {expected}\n      实际: {got}")

    print(f"不应脱敏组：{len(SHOULD_NOT_MASK)} 条")
    for text in SHOULD_NOT_MASK:
        got = apply_replacements(text, engine.find_spans(text))
        if got == text:
            print(f"  PASS {text}（未改动）")
        else:
            failed.append((text, text, got))
            print(f"  FAIL {text} 被误脱敏为: {got}")

    print(f"\n共 {TOTAL_CASES} 条用例，失败 {len(failed)} 条")
    return not failed


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    ok = run()
    sys.exit(0 if ok else 1)
