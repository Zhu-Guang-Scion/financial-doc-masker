def run() -> bool:
    failed = []
    engine = RuleEngine(MaskOptions(mask_company=True, mask_person=True, person_loose=True))

    print(f"不应脱敏组：{len(SHOULD_NOT_MASK)} 条")
    for text in SHOULD_NOT_MASK:
        got = engine.find_spans(text)
        company_hits = [s for s in got if s.rule in ("company", "security_code")]
        if company_hits:
            failed.append((text, [(s.text, s.replacement) for s in company_hits]))
            print(f"  FAIL {text} -> {[(s.text, s.confidence) for s in company_hits]}")
        else:
            print(f"  PASS {text}")

    print(f"应脱敏组：{len(SHOULD_MASK)} 条（每条独立引擎，别名从 ABC 起）")
    for text, expected in SHOULD_MASK:
        eng = RuleEngine(MaskOptions(mask_company=True, mask_person=True, person_loose=True))
        from app.handlers.text_replacement import apply_replacements
        got = apply_replacements(text, eng.find_spans(text))
        if got == expected:
            print(f"  PASS {text} -> {got}")
        else:
            failed.append((text, expected, got))
            print(f"  FAIL {text}\n      期望: {expected}\n      实际: {got}")

    total = len(SHOULD_NOT_MASK) + len(SHOULD_MASK)
    print(f"\n共 {total} 条用例，失败 {len(failed)} 条")
    return not failed


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    ok = run()
    sys.exit(0 if ok else 1)
