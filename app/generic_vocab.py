def _dedupe(raw: tuple[tuple[str, str], ...]) -> tuple[tuple[str, str], ...]:
    """去重构建：一词保留首个来源（种子一→五→补种顺序）；重词条目丢弃。"""
    seen: set[str] = set()
    out: list[tuple[str, str]] = []
    for w, src in raw:
        if w in seen:
            continue
        seen.add(w)
        out.append((w, src))
    return tuple(out)


