def load_mapping_csv(path: str) -> dict:
    """加载外部映射对照表 CSV（列：原文,替换为；首行表头自动识别）。

    编码依次尝试 UTF-8(-BOM) / GBK。
    """
    _p = Path(path)
    if not _p.exists():
        # v2.1.9（R1-P2-6）：人话报错（原裸 FileNotFoundError 回溯对终端用户不友好）
        raise FileNotFoundError(
            f"映射对照表 CSV 不存在：{_p}（请在界面④区重新选择映射表文件）")
    raw = _p.read_bytes()
    content = None
    for enc in ("utf-8-sig", "gbk", "utf-8"):
        try:
            content = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    if content is None:
        raise ValueError("对照表 CSV 编码无法识别（请使用 UTF-8 或 GBK 保存）")
    mapping = {}
    for i, row in enumerate(csv.reader(io.StringIO(content))):
        if not row or not row[0].strip():
            continue
        if i == 0 and ("原文" in row[0] or "原词" in row[0]):
            continue  # 表头
        orig = row[0].strip()
        repl = row[1].strip() if len(row) > 1 else "***"
        mapping[orig] = repl
    return mapping


