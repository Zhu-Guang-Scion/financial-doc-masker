_JOB_ANNOTATION_HEAD = 14


def _label_anchor_spans(text: str) -> set:
    """v2.0.4：行首职务标签锚定 + 无标签名单行版式锚定 → 强证据 span 集。

    返回值与 _enum_evidence 同构（{(start, end), …}），在 _person_candidates
    主循环中按强上下文证据（score=3）放行；候选仍走完整评分/闸门流水线
    （词条否决/构字否决/黑名单等不豁免，不绕闸）。两形态（语料实测）：

    - A 行首标签锚定：封闭清单标签（组长/副组长/成员，含 0~2 全角/半角空格
      变体）+ 冒号 → 名单区（顿号或 ≥2 空格分隔的单元）内 2~4 字纯 CJK
      单元锚定（正文标签行与竖排名单行实录）；
    - B 无标签名单行：行首人名单元（2~4 字，含排版接缝内嵌空格形态）+
      ≥2 空格 + 职务括注（头部含职务词）→ 行首单元锚定（名单实录：
      「林晏清   党委书记」续行形态）。

    判别规则（关键）：A 形态标签后首单元含结构词 → 整行不产生人名候选
    （结构词排除 > 标签锚定）。
    与排版接缝机制协同：接缝（_person_gap_spans）内的 1~2 空格不作为单元分隔
    （「唐某」保持单一单元，「琼   党」3 空格为分隔）；镜像重扫文本
    （_merge_gap_space_candidates）上本函数重入，坐标天然对齐——跨接缝
    候选仍仅由镜像路径回收、主路径仅匹配连续单元，同人名同位置不双生成。
    """
    out: set = set()
    if not text:
        return out
    gspans = _person_gap_spans(text)

    def _in_seam(a: int, b: int) -> bool:
        return any(a < ge and gs < b for gs, ge in gspans)

    def _unit_is_name(t: str) -> bool:
        """单元人名形态：2~4 个汉字（允许接缝内空格），无其余字符类别。"""
        eff = 0
        for ch in t:
            if _cjk(ch):
                eff += 1
            elif ch not in _GAP_SPACE_CHARS:
                return False
        return 2 <= eff <= 4

    def _try_anchor(a: int, b: int, t: str) -> None:
        if _unit_is_name(t) and not any(w in t for w in _LABEL_STRUCT_WORDS):
            out.add((a, b))

    pos = 0
    for raw in text.split("\n"):
        base = pos
        pos += len(raw) + 1
        line = raw.rstrip("\r")
        lm = _LABEL_HEAD_RE.match(line)
        if lm is not None:
            # ---- A 形态：行首标签锚定 ----
            seg_off = lm.end()
            seg = line[seg_off:]
            # 名单区单元切分：顿号或 ≥2 空格（接缝内空格除外）
            units: list = []
            n = len(seg)
            start = 0
            i = 0
            while i < n:
                ch = seg[i]
                if ch == "、":
                    units.append((start, i))
                    start = i + 1
                    i += 1
                elif ch in _GAP_SPACE_CHARS:
                    j = i
                    while j < n and seg[j] in _GAP_SPACE_CHARS:
                        j += 1
                    if j - i >= 2 and not _in_seam(base + seg_off + i,
                                                   base + seg_off + j):
                        units.append((start, i))
                        start = j
                    i = j
                else:
                    i += 1
            units.append((start, n))
            parsed = []
            for a, b in units:
                t = seg[a:b].strip(" \u3000\t")
                if t:
                    parsed.append((a, b, t))
            # 判别规则：标签后首单元含结构词 → 整行不产生人名候选
            if parsed and any(w in parsed[0][2] for w in _LABEL_STRUCT_WORDS):
                continue
            for a, b, t in parsed:
                _try_anchor(base + seg_off + a, base + seg_off + b, t)
        else:
            # ---- B 形态：无标签名单行（人名单元 + ≥2 空格 + 职务括注） ----
            n = len(line)
            i = 0
            while i < n and (_cjk(line[i]) or (
                    line[i] in _GAP_SPACE_CHARS
                    and _in_seam(base + i, base + i + 1))):
                i += 1
            unit = line[:i]
            # 单元后须紧跟 ≥2 个空格（0~1 空格直接接字=普通行文，不锚定）
            if i < n and line[i] in _GAP_SPACE_CHARS:
                j = i
                while j < n and line[j] in _GAP_SPACE_CHARS:
                    j += 1
                if j - i >= 2 and _unit_is_name(unit) \
                        and not any(w in unit for w in _LABEL_STRUCT_WORDS):
                    note = line[j:j + _JOB_ANNOTATION_HEAD]
                    if any(w in note for w in _JOB_ANNOTATION_WORDS):
                        out.add((base, base + i))
    return out


