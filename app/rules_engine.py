# 千档解析包装。utils.parse_amount 只识别 万/亿 两档（既有口径
# 口径，「千」在其下仅以千位分隔符语境出现），「2千元」类形态 float 直接
# 失败返回 None → _amount_ok 会把 AMOUNT_RE 新放行的千档候选整笔否决
# （词档补了、闸没补 = 等于没修）。本包装只对「X千」形态（可带 ￥¥ 字头/
# 元字尾/制版空格/逗号分节）等价换算 ×1000，其余形态原样透传 parse_amount
# （零行为差）；千位分隔符语境（1,000 / 12,345.67）不含「千」字，天然不走
# 本包装。
_QIAN_AMOUNT_RE = re.compile(
    r"^\s*(?:(?:￥|¥)\s*)?(\d[\d,]*(?:\.\d{1,2})?)\s*千\s*(?:元)?\s*$")


def _parse_amount_qian_base(s: str):
    """千档基础解析（v2.0.2 A 线原逻辑；复合档增强版见锚后 _parse_amount_qian）：
    「2千元/2.5 千元/￥2千」→ ×1000，否则透传 utils.parse_amount。"""
    if "千" not in s:
        return parse_amount(s)
    m = _QIAN_AMOUNT_RE.match(s)
    if m is None:
        return parse_amount(s)
    return float(m.group(1).replace(",", "")) * 1000.0

