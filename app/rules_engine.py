    def _company_candidates(self, text: str) -> list:
        """公司/法人机构名称：三段式流水线（v2）。

        第一步 左边界吸附（snap）：候选左边界落在 jieba 词内时向左扩展到词边界，
        修复"商银行股份有限公司"这类左截断（F 类）。
        第二步 左粘连修整（trim）：反复剥离左缘的日期/数字、连词、动词前缀
        （支付/结转/确保/任…），修复 B 类粘连；映射表记录修整后的最终串。
        第三步 实体性校验：后缀分级（完整后缀强候选 / 裸"公司"弱候选）、
        字号校验（长度、jieba 常用词、词性、行业泛指、量化泛指、法律保护区），
        拒绝 C/D/E 类泛称。泛称"公司"一律不脱敏。
        """
        out = []
        pay_name_spans: list = []  # v1.7：支付粘连剥离出的人名区段
        # v1.7：全角括号归一化——「示例科技（北京）科技有限公司」类全角地名
        # 注记的跨越判断失效（半角正常），1:1 字符替换索引不变，命中区间
        # 仍按原文切片
        text = text.replace("（", "(").replace("）", ")")
        protected = self._protected_law_spans(text)
        prev_strong_end = -1  # 分公司/子公司纯地名字号的父公司上下文判定
        for m in COMPANY_SUFFIX_RE.finditer(text):
            suffix = m.group()
            end = m.end()
            j = m.start()
            adj_break = False  # v1.6.5：按匹配复位——v1.6.3 前置初始化导致一次
            # 邻接后同文本所有后续匹配的 snap 修复全部失效（曾因此漏修）
            stopped_at_prose = False  # v1.6.4：回溯是否停在公文大词边界（合法截停）
            snapped = False  # v1.6.5：snap 是否移动过左边界（移动后不再触发 A 类守卫）
            walk_capped = False  # v1.6.6：回溯是否撞到 30 字上限（唯一非法残留形态）
            while j > 0 and (m.start() - j) < 30                     and text[j - 1] in _NAME_CHARS and text[j - 1] not in _STOP_CHARS_BEFORE_NAME:
                if any(text[:j].endswith(S) for S in _ADJ_BREAK_SUFFIXES):
                    adj_break = True
                    break  # 已贴到前一家公司的公司系后缀：两家机构名相邻，各自独立
                if text[j - 2:j] in _PROSE_BIGRAM_BEFORE_NAME:
                    stopped_at_prose = True
                    break  # 再往前是"制度"这类公文词，属正文而非字号
                j -= 1
            # v1.6.9 括号区划注记跨越：“示例家居(浙江)有限责任公司”的后缀左邻
            # 是 )（不在 _NAME_CHARS）→ 回溯即停、字号为空而漏检。跨过括号
            # 段后继续常规回溯，把“示例家居(浙江)”整体并入字号。
            if j > 0 and j == m.start() and text[j - 1] in ")）":
                last_pm = None
                for pm in _PAREN_NOTE_RE.finditer(text, max(0, j - 14), j):
                    last_pm = pm
                # 括号前 run 含连词（及其/及各/以及/与其）→ 泛指
                # 短语「…公司及其各控股（分）子公司」，不跨越（真实公司名由
                # 自身后缀独立命中；跨越会整句吸附）
                if last_pm is not None and any(
                        cb in text[max(0, last_pm.start() - 30):last_pm.start()]
                        for cb in ("及其", "及各", "以及", "与其")):
                    last_pm = None
                if last_pm is not None and last_pm.end() == j:
                    # 括号前须有 ≥2 个连续名字字符（示例家居 ✓；“分（子）公司”
                    # 的“分”仅 1 字 → 惯用语，不跨越）
                    pre = text[:last_pm.start()]
                    k2 = len(pre)
                    n_name = 0
                    while k2 > 0 and pre[k2 - 1] in _NAME_CHARS:
                        # 纯名字符连续 run 计数（不再排除 停用字）——
                        # 「示例科技(北京)」括号前的字均为品牌组成部分（含停用字）；惯用语
                        # 「分（子）公司」仍因 run 长度 1 <2 被拦
                        n_name += 1
                        k2 -= 1
                    if n_name >= 2:
                        # 直接按 n_name 定界——括号前的名字串已经
                        # n_name 计数验证过连续性，二次回溯若再走停用字条件，
                        # 会被「示例科技(北京)」的科/技 截停成「技(北京)」而
                        # 整名漏检（独立校验发现的漏报根因之一）
                        j = last_pm.start() - n_name
                        if j > 0 and text[j - 2:j] in _PROSE_BIGRAM_BEFORE_NAME:
                            stopped_at_prose = True
            # 死代码清理：原「else: pass」空分支无效果，删除
            if (m.start() - j) >= 30 and text[j - 1] in _NAME_CHARS \
                    and text[j - 1] not in _STOP_CHARS_BEFORE_NAME:
                walk_capped = True
            # 断词守卫（A 类）：仅当回溯撞到 30 字上限（无法确定词边界的极端
            # 长串）时否决。停用字/大词/非名字符截停都是结构性合法边界——
            # “适用于示例甲家居…”停在“于”后、“制度适用…”停在大词前，
            # 若按词典词频否决会把整句真实企业名全部漏掉（v1.6.6 用户实测）
            if walk_capped and j >= 2 \
                    and (self._get_jieba().dt.FREQ.get(text[j - 2:j]) or 0) >= 500:
                self._trace("reject", "company", text[j:end], "gate=walk_cap_freq")
                continue
            # "中国"开头的机构名：'中' 在停用字表，但名称以中国起步时保留
            if j > 0 and text[j - 1] == "中" and text[j:j + 1] == "国":
                j -= 1
            # 第一步 吸附（snap）：左边界切进 jieba 词内（词有 ≥2 字被丢在左侧，
            # 或被丢的单字非虚词）→ 向左扩展到词边界；单字虚词（了/把…）不吸附；
            # v1.6.4：公文大词（制度/详见…）不吸附——大词边界截停是合法左边界；
            # v1.6.5：多字词典词一律吸附，且循环吸附到词边界
            # （“某科|项目管理咨询有限公司”：项目管理→某科 一路吸齐）
            if j > 0 and not adj_break:
                # O(n²) 早退：j 在 while 内单调左移、
                # token 序按起点升序且无缝覆盖——满足「a<j<=b」的 token 全文
                # 唯一且必是「最后一个 a<j」的 token；指针 _snap_p 随 j 单调
                # 左移全程一次扫穿，选中 token 与逐次全量重扫完全一致（零行为差）。
                _snap_toks = self._segment(text)
                _snap_p = len(_snap_toks)
                while j > 0:
                    while _snap_p > 0 and _snap_toks[_snap_p - 1][1] >= j:
                        _snap_p -= 1
                    tok = None
                    if _snap_p > 0:
                        _w, _a, _b = _snap_toks[_snap_p - 1]
                        if _a < j <= _b and _b <= m.start():
                            tok = (_w, _a, _b)
                    if tok is None:
                        break
                    w, a, b = tok
                    if w in _PROSE_BIGRAM_BEFORE_NAME or text[a] not in _NAME_CHARS:
                        break
                    # （v1.6.9 行文前缀在词性校验处剥离重验，见下方“弱词性
                    # 前缀剥离”——snap 保持宽容以兼容 某正信/某科类名字词）
                    pass
                    # v2.1.6 字号内嵌连词跨越：
                    # 单字「与」被丢在左侧时，若其左邻是普通名字字符（∈
                    # _NAME_CHARS 且 ∉停用 ∉功能尾字）——即「名字字|与|名字
                    # 串」三明治——判为字号内连词而非句法连词，允许吸附跨越
                    # （发票案例：北京示例寅餐饮管理有限公司——回溯在「与」
                    # 截停 + jieba 把生僻字号切成单字词、单字「与」∈
                    # _FUNCTION_TAIL 被吸附拒斥 → 词干起点=字号末字，
                    # 品牌前两字泄漏）。句法面由既有闸拦截：「A公司与B
                    # 公司」=回溯层 adj_break；「包括与适用…公司」=实体性
                    # 校验（_COMPANY_NAME_PREFIX_BLACKLIST/泛指闸）；误跨的
                    # 最坏结果=多遮一段疑似字号（P0 宁多遮不漏）。集合只收
                    # 「与」（本案实测字；「或/并」句法性更强未见字号用例，
                    # 「和/及」暂不放开）。
                    conj_bridge = (
                        w == "与" and (b - a) == 1 and a >= 1
                        and text[a - 1] in _NAME_CHARS
                        and text[a - 1] not in _STOP_CHARS_BEFORE_NAME
                        and text[a - 1] not in _FUNCTION_TAIL
                        # 句法连词否决：「A公司与B公司」的「与」左邻虽是
                        # 名字字符（司），但其左侧串以公司系后缀结尾——
                        # 与回溯层 adj_break 同款口径，后缀右贴的「与」是
                        # 句法连词不跨越（否则两家并一家）。
                        and not any(text[:a].endswith(S)
                                    for S in _ADJ_BREAK_SUFFIXES))
                    if conj_bridge or (j - a) >= 2 or (b - a) >= 2 or (
                            text[a] not in _FUNCTION_TAIL
                            and text[a] not in _STOP_CHARS_BEFORE_NAME):
                        j = a
                        snapped = True
                        continue
                    break
            # 第二步 修整（trim）：剥离左缘日期/数字、版本号、支付粘连、连词、动词前缀
            trimmed = False
            while True:
                head = text[j:end]
                dm = _COMPANY_TRIM_DATE_RE.match(head)
                if dm and len(head) - dm.end() >= 2:
                    j += dm.end()
                    trimmed = True
                    continue
                # 表头标签词前缀剥离——行拼接后「规章文件名称示例甲
                # 家居股份有限公司」类标签+全名同行（标题格实测），
                # 回溯被「章」停用字截停后候选以「章文件名称…」起头被否决；
                # 剥离标签词让真实公司名独立成候选
                lm2 = _LABEL_PREFIX_RE.match(head)
                if lm2 and len(head) - lm2.end() >= 2:
                    j += lm2.end()
                    trimmed = True
                    continue
                vm2 = _COMPANY_TRIM_VER_RE.match(head)
                if vm2 and len(head) - vm2.end() >= 2:
                    j += vm2.end()  # 文档版本号前缀（A4示例甲… → 示例甲…）
                    trimmed = True
                    continue
                pm = _COMPANY_TRIM_PAY_RE.match(head)
                if pm and len(head) - pm.end() >= 4:
                    # v1.7：被剥离的「人名+付」中人名按 force 档补遮
                    # （某甲付乙市保洁… → 某** 与 乙市保洁… 分别脱敏）
                    pay_name = pm.group()[:-1]
                    if 2 <= len(pay_name) <= 3:
                        pay_name_spans.append((j, j + len(pay_name)))
                    j += pm.end()  # 人名+支付动词粘连（某甲付乙市保洁… → 乙市保洁…）
                    trimmed = True
                    continue
                vm = None
                for v in _COMPANY_TRIM_VERBS:
                    if head.startswith(v) and len(head) - len(v) >= 2:
                        vm = v
                        break
                if vm:
                    j += len(vm)
                    trimmed = True
                    continue
                # v1.6.4 通用动词前缀剥离：首 token 是高频动词/副词/介词等
                # 词典词条（促进/适用/支持/纳入/针对…）→ 是行文动词不是字号，
                # 剥离后剩余部分照常通过全部实体性校验（词典外字号不受影响）
                if len(head) > len(suffix) + 2:
                    tok_w, tok_a, tok_b = None, None, None
                    for w, a, b in self._segment(text):
                        if a == j:
                            tok_w, tok_a, tok_b = w, a, b
                            break
                        if a > j:
                            break
                    if tok_w and (self._get_jieba().dt.FREQ.get(tok_w) or 0) >= 100:
                        from jieba import posseg
                        tag = posseg.dt.word_tag_tab.get(tok_w, "")
                        if tag[:1] in "vdcpqtm" and tag[:2] != "nr":
                            j += len(tok_w)
                            trimmed = True
                            continue
                if head and head[0] in _COMPANY_TRIM_CONJ and len(head) >= 3:
                    j += 1
                    trimmed = True
                    continue
                break
            # 合伙企业/事务所的括号注记（（有限合伙）等）并入名称
            paren = _PARTNERSHIP_PAREN_RE.match(text, end)
            if paren:
                end = paren.end()
            name = text[j:end]
            stem = text[j:m.start()]  # 剥掉后缀后的字号
            # v1.6.9：字号首字符必须是名字字符（拦“（子）公司”类括号惯用语
            # 被 snap/trim 拼成候选）；“中国”开头的全国性机构例外放行
            if (stem[:1] in _STOP_CHARS_BEFORE_NAME or stem[:1] not in _NAME_CHARS) \
                    and not stem.startswith("中国"):
                # 停用字/非名字字符开头的碎片（中本/后本/（子）类）否决；
                # 但首词为多字词的（某正信会计师事务所——snap 循环修复
                # 截断后的正常形态）放行
                _first_tok_end = next((b for w, a, b in self._segment(stem) if a == 0), 1)
                if _first_tok_end < 2:
                    continue
            # v1.6.6：书名号内不再一刀切——强/弱公司后缀名称是真实企业引用
            # （《…存货资产盘点管理办法》内的“示例甲家居股份有限公司”）照常
            # 脱敏；法规名（《会计法》，无公司后缀）仍被否决
            if any(j < pe and ps < end for ps, pe in self._book_title_spans(text)) \
                    and suffix not in _LEGAL_SUFFIX_SET:
                self._trace("reject", "company", name, "gate=book_title")
                continue
            if len(stem) < 2:
                self._trace("reject", "company", name, "gate=no_stem")
                continue  # 无字号
            # v1.6.4 修复：行文动词被回溯吸进名称（“促进示例甲家居股份有限
            # 公司”“适用示例甲家居股份有限公司”）时，前缀黑名单原先直接
            # 作废整个候选 → 整句漏脱敏。现改为剥离黑名单前缀后重新校验，
            # 剥到字号不足 2 字仍命中才否决。
            while True:
                if name[:2] in _COMPANY_NAME_PREFIX_BLACKLIST and (m.start() - (j + 2)) >= 2:
                    j += 2
                elif name[:1] in _COMPANY_NAME_PREFIX_BLACKLIST and (m.start() - (j + 1)) >= 2:
                    j += 1
                else:
                    break
                trimmed = True
                name = text[j:end]
                stem = text[j:m.start()]
            if name[:2] in _COMPANY_NAME_PREFIX_BLACKLIST or name[:1] in _COMPANY_NAME_PREFIX_BLACKLIST:
                self._trace("reject", "company", name, "gate=prefix_blacklist")
                continue

            # ---- 第三步 实体性校验 ----
            strong = suffix in _STRONG_SUFFIXES
            gated = suffix in _GATED_SUFFIXES
            if gated and not self.opt.include_institutions:
                self._trace("reject", "company", name, "gate=institution_off")
                continue  # 扩展机构识别默认关闭（大学/研究院/医院/银行等）
            # 法律保护区（书名号 + 无书名号法律名）重叠 → 否决；
            # v1.6.6：强/弱公司后缀的名称放行——《…存货资产盘点管理办法》中
            # 引用的“示例甲家居股份有限公司”是真实企业必须脱敏；
            # 《会计法》《银行法》等法规名不带公司后缀，仍被否决
            if any(j < pe and ps < end for ps, pe in protected) \
                    and suffix not in _LEGAL_SUFFIX_SET:
                self._trace("reject", "company", name, "gate=law_protected")
                continue
            # 法律名黑名单（字号命中即否决，含"中华人民共和国"前缀形态）
            stem_core = stem[7:] if stem.startswith("中华人民共和国") else stem
            if stem_core in _LAW_NAMES:
                continue
            # 量化泛指前缀（强弱候选都否决）：主要子公司/上级子公司/多家全球航空公司…
            if stem.startswith(_QUANT_PREFIXES):
                self._trace("reject", "company", name, "gate=quant_prefix")
                continue
            # 事务所泛称判定：剥掉职业后缀（会计师/会计）后无有效字号 → 否决
            # （"更换会计师事务所"剥后为"更换"=动词 → 否决；
            #   "某正信会计师事务所"剥后为"某正信"=真实字号 → 放行）
            if suffix == "事务所":
                core = stem
                if core.endswith("会计师"):
                    core = core[:-3]
                elif core.endswith("会计"):
                    core = core[:-2]
                if core == "" or core in _COMPANY_TRIM_VERBS or len(core) < 2:
                    self._trace("reject", "company", name, "gate=firm_generic")
                    continue
            conf = ""
            # ---- 字号校验（强弱候选统一；实体词性 nt/nz/nr/nrt 例外放行）----
            if stem in COMMON_WORDS or stem in _COMPANY_STEM_BLACKLIST:
                self._trace("reject", "company", name, "gate=stem_lexicon")
                continue
            if stem in _INDUSTRY_WORDS or any(stem.endswith(i) for i in _INDUSTRY_WORDS):
                self._trace("reject", "company", name, "gate=industry_generic")
                continue  # 行业泛指：化工公司/物流公司/软件和信息技术服务公司…
            if stem.startswith(_QUANT_PREFIXES):
                self._trace("reject", "company", name, "gate=quant_prefix")
                continue  # 量化泛指：主要子公司/多家全球航空公司…
            # v1.6.3 prose 字号否决（1330 样本）；v1.6.5 细化防误杀真实企业名
            # （某消费金融/某科项目管理咨询 等名称含 prose 词块的真实公司）：
            # - 弱候选（裸公司/集团）：含任一 prose 词块或以尾词收尾 → 否决；
            # - 强候选：仅当 prose 词块位于字号开头、或命中 ≥2 个不同词块、
            #   或以行文尾词收尾时否决（单个居中 prose 词块放行）
            if any(stem.startswith(k) for k in _COMPANY_RANK_PREFIX):
                self._trace("reject", "company", name, "gate=rank_prefix")
                continue  # 职务/职等前缀（副总裁集团/高级经理类）非企业字号
            if self._stem_prose_veto(stem, suffix):
                self._trace("reject", "company", name, "gate=prose_stem")
                continue
            pos = self._pos_tags(stem)
            flags = list(pos.values())
            first_flag = flags[0] if flags else ""
            entity_flag = first_flag in ("nt", "nz", "nr", "nrt")
            if first_flag[:1] in _WEAK_POS_VETO and not entity_flag:
                # v1.6.9 弱词性前缀剥离重验：snap 吸附进来的行文前缀
                # （不含/适用于——示例家居(浙江)有限责任公司 漏检根因）按
                # token 剥离（≤4字、非实体词性）后重算字号；剥完仍有
                # ≥2 字且不再弱词性开头则继续校验，否则按原逻辑否决
                stripped_ok = False
                for _ in range(3):
                    toks = self._segment(stem)
                    if not toks or toks[0][1] != 0:
                        break
                    w0, a0, b0 = toks[0]
                    # 词性独立查询：_pos_tags 的 posseg 切分与 tokenize 不
                    # 总是一致（“不含”tokenize 为一词、posseg 拆两字）
                    from jieba import posseg
                    tag0 = posseg.lcut(w0)[0].flag if w0 else ""
                    if tag0 and tag0[:1] in "vdacpumqt" \
                            and tag0[:2] not in ("nr", "nt", "nz") \
                            and 1 <= b0 - a0 <= 4 and (m.start() - (j + b0)) >= 2:
                        j += b0
                        trimmed = True
                        name = text[j:end]
                        stem = text[j:m.start()]
                        pos = self._pos_tags(stem)
                        flags = list(pos.values())
                        first_flag = flags[0] if flags else ""
                        entity_flag = first_flag in ("nt", "nz", "nr", "nrt")
                        stripped_ok = True
                        continue
                    break
                if first_flag[:1] in _WEAK_POS_VETO and not entity_flag:
                    self._trace("reject", "company", name, "gate=pos_veto")
                    continue  # 动词/形容词/连词/介词/数词等开头：促使公司/如果公司/增加子公司…
                if stripped_ok:
                    # 剥离后重跑 prose 校验（行文前缀可能含业务词块）
                    if self._stem_prose_veto(stem, suffix):
                        self._trace("reject", "company", name, "gate=prose_stem_restripped")
                        continue
            jf = self._get_jieba().dt.FREQ.get(stem)
            tag = pos.get(stem, "")
            non_entity = tag not in ("nt", "nz", "nr", "nrt")
            if suffix in _WEAK_SUFFIXES:
                # 弱候选（裸"公司"）：字号含动词/副词 token → 行文碎片否决
                # （资金要满足公司/公允价值按公司）
                if any(f[:1] in "vdacpumqt" for f in flags):
                    self._trace("reject", "company", name, "gate=weak_verb_frag")
                    continue
                if jf and jf >= 20 and non_entity:
                    self._trace("reject", "company", name, f"gate=freq_weak;jf={jf}")
                    continue
                # 死代码清理：下邻同条件重复语句（复制
                # 粘贴残留）删除——弱候选中高频非实体词条否决以本条为准
            else:
                # 强候选：仅超高频非实体词条否决（放过 某某集团 freq=416/tag=r 占位名）
                if jf and jf >= 500 and non_entity:
                    self._trace("reject", "company", name, f"gate=freq_strong;jf={jf}")
                    continue
            entity_tag = tag in ("nt", "nz", "nr")
            if suffix in _WEAK_SUFFIXES:
                conf = PERSON_CONF_MID if entity_tag else PERSON_CONF_LOW
            else:
                # 强候选
                if suffix in ("分公司", "子公司") and (stem in _PLACE_NAMES
                        or (stem.endswith(("市", "省")) and stem[:-1] in _PLACE_NAMES)):
                    if prev_strong_end != j:
                        self._trace("reject", "company", name, "gate=place_no_parent")
                        continue  # 纯地名字号分公司：无紧邻父公司名上下文 → 否决
                    conf = PERSON_CONF_LOW  # 有父公司上下文：低置信放行
                elif gated:
                    conf = PERSON_CONF_MID  # 扩展机构（手动开启）
                else:
                    conf = PERSON_CONF_MID if trimmed else PERSON_CONF_HIGH
            # 死代码清理：删「or name in _PERSON_BIZ_TAIL_SET」
            # ——该集合为单字集，name 恒 >=4 字，成员判定恒 False（死条件）。
            # 定义行（:495 附近，575 行号审计锚之前）原样保留不动。
            if name in _BRAND_STOP_ALL or name in NON_NAME_BLACKLIST                     or name in _COMPANY_STEM_PROSE:
                self._trace("reject", "company", name, "gate=generic_name")
                continue  # 泛词名（网约车/报实销类）不注册为公司实体
            if name[:1] in "（(" and name.endswith(("子公司", "分公司", "公司"))                     and len(name) <= 8:
                self._trace("reject", "company", name, "gate=bracket_generic")
                continue  # 括号泛指（（分）子公司类）非企业实体
            out.append(_Cand(j, end, "company", name,
                             self._company_alias_for(name), 0, conf))
            if strong:
                prev_strong_end = end
                # v1.6.6 品牌前缀派生：全名脱敏时注册品牌词（示例甲家居股份
                # 有限公司 → 示例甲），本块及后续文本中品牌独立出现处跟随脱敏
                self._register_brand(text, j, end, name, out)
        # v1.7 支付粘连剥离的人名回收（某甲 付XX公司 → 某**）
        for ps0, ps1 in pay_name_spans:
            blk = text[ps0:ps1]
            if any(ps0 < e and ps1 > st for st, e in
                   ((c.start, c.end) for c in out)):
                continue
            for sp2 in self._person_candidates(blk, force_person=True):
                if sp2.text == blk:
                    out.append(_Cand(ps0, ps1, sp2.rule, blk,
                                     sp2.replacement, sp2.confidence))
                    break
        return out

    def _register_brand_extras(self, base: str, repl: str) -> None:
        """品牌注册跟随项（v1.7 闭环加固）：

        繁体别名：OCR 对繁体/艺术字 logo 识别输出繁体字形（实测
        某品牌繁体字形案例 conf 0.98），别名进简称表后同一替换语义生效。
        slogan 注册管线移除——slogan 自早期版本起
        已移出脱敏范围（原 _BRAND_SLOGANS 永空表），管线不可达。
        """
        repl = repl or "***"
        t = _s2t(base)
        if t != base and t not in self._short_names:
            self._short_names[t] = repl

    def _register_brand(self, text: str, j: int, end: int, name: str, out: list) -> None:
        """v1.6.6 品牌前缀派生：

        全名（示例甲家居股份有限公司）脱敏时派生品牌词（示例甲）注册进
        简称表，并为本块文本中品牌独立出现处（"示例甲与发包方签合同"
        "示例甲木门""示例甲®"）生成跟随脱敏候选。派生规则见 _derive_brand。
        """
        full_alias = self._company_alias_for(name)
        base, brand_repl = _derive_brand(name, full_alias)
        if not base:
            return
        if base in _BRAND_STOP_ALL:
            return  # 截断形态（家居股份有限公司类）派生泛词品牌守卫
        if base in self._short_names and self._short_names[base] != "***":
            return  # 已按真实别名/简称注册，不覆盖
        # 静态占位（***）或未注册 → 覆盖为真实别名
        self._short_names[base] = brand_repl
        self._register_brand_extras(base, brand_repl)
        # 真品牌注册后，撤销同名静态注入（裸品牌改跟随别名 ABC）
        for w in (base, _s2t(base)):
            if w in getattr(self, "_static_brand_words", ()):
                self._static_brand_words.discard(w)
                if w in self._word_keys:
                    self._word_keys.remove(w)
                    # 同步清代号死条目（防繁体品牌形撞自定义词时
                    # 同批双代号——custom 通道敏N 与 company 通道 *** 不一致）
                    self._custom_replacements.pop(w, None)
        # 本文本块中品牌（含繁体别名）独立出现处生成候选
        # （与全名重叠处由消解阶段丢弃；_dict_candidates 先于公司管线
        # 执行，注册当块的新别名必须在此手动补候选）
        keys = [base]
        t = _s2t(base)
        if t != base:
            keys.append(t)
        for key in keys:
            start = 0
            while True:
                i = text.find(key, start)
                if i < 0:
                    break
                out.append(_Cand(i, i + len(key), "company", key,
                                 brand_repl if key in (base, t) else "***"))
                start = i + len(key)

    def _company_alias_for(self, original: str) -> str:
        """机构名替换策略：同一原名在整个批次内使用固定的无意义英文别名。

        第 1 家 -> ABC公司，第 2 家 -> DEF公司，依次类推（循环 9 组后加序号）。
        非公司类机构（大学/基金会/事务所等）别名为 英文别名+自身后缀
        （如 ABC事务所），保留机构类型、隐去名称。
        """
        if original not in self._company_alias:
            n = len(self._company_alias) + 1
            triplet = _ALIAS_TRIPLETS[(n - 1) % len(_ALIAS_TRIPLETS)]
            seq = (n - 1) // len(_ALIAS_TRIPLETS)
            # 后缀：取名称结尾处命中的机构后缀；合伙括号注记计入；默认“公司”
            probe = original
            suffix = "公司"
            m = _PARTNERSHIP_PAREN_RE.search(probe)
            paren_text = probe[m.start():] if m else ""
            stem = probe[:m.start()] if m else probe
            for s in sorted(_COMPANY_SUFFIX_LIST, key=len, reverse=True):
                if stem.endswith(s):
                    suffix = s
                    break
            tail = suffix + paren_text
            alias = f"{triplet}{'' if seq == 0 else seq + 1}{tail}"
            self._company_alias[original] = alias
        # 守卫 dict 可能否决了写入（泛词名）——返回 *** 兜底，
        # 不可 KeyError（KeyError 会被页级异常处理器吞成整页跳过）
        return self._company_alias.get(original, "***")

    def _title_standalone(self, text: str, tstart: int, title: str) -> bool:
        """称谓后缀（王总/李工/张经理 的 总/工/经理…）是否独立成称谓。

        v1.6.1 修复：称谓后须为边界（标点/空格/结尾）；若与后邻汉字构成真实
        词典词（示例丁工厂/示例贸易工行），或称谓本身与后文均为词典词
        （向上级主管部门/季度会计报表），则它是普通名词而非称谓。
        “王总在会上指出”（总在 非词）仍放行。
        """
        tlen = len(title)
        nxt = text[tstart + tlen:tstart + tlen + 1]
        if not nxt or not _cjk(nxt):
            return True  # 边界明确
        freq = self._get_jieba().dt.FREQ
        if tlen == 1:
            return not freq.get(title + nxt)  # 工+厂=工厂 → 否决；总+在 → 放行
        # 双字称谓：称谓是高频词典词且后面紧跟的二字也是词典词 → 机构语块
        if (freq.get(title) or 0) >= 100:
            nxt2 = text[tstart + tlen:tstart + tlen + 2]
            if (freq.get(nxt2) or 0) >= 100:
                return False
        return True

    def _fragment_dict_veto(self, w: str) -> bool:
        """词条词性否决（A'）：候选本身是词典词条且词性为动词/名词/副词等
        非名字类（申请/施工/查询/应该/文件名/单号…）→ 无论证据多强都不是人名。
        名字类词性 nr/nrfg/nrt/ns/nt/nz 及词典外词放行（李强nrfg/高山ns/白石nr）。"""
        jieba = self._get_jieba()
        freq = jieba.dt.FREQ.get(w)
        if not freq:
            return False
        from jieba import posseg
        tag = posseg.dt.word_tag_tab.get(w, "")
        return tag not in ("nr", "nrfg", "nrt", "nr1", "nr2", "ns", "nt", "nz", "x", "eng")

    def _fragment_given_veto(self, w: str) -> bool:
        """构字否决（B，仅弱证据档调用）：候选切分出的多字真实词条（频次≥100）
        含非名字用字（按:照/规:定/公:司/预:算…）→ 是词组碎片而非人名。
        某晨光(晨光90)/某鹏程(鹏程40)/某云福(白云,白/云均名用字) 不受影响。"""
        for t, a, b in self._segment(w):
            if b - a < 2:
                continue
            freq = self._get_jieba().dt.FREQ.get(t)
            if freq and freq >= 100 and any(ch not in GIVEN_CHARS for ch in t):
                return True
        return False

    def _verb_is_speech(self, verb: str, text: str, vend: int) -> bool:
        """陈述动词是否为独立“说话”义：与后字构成真实词条（说+明=说明、
        称+为=称为）时是普通名词语块（毛利额说明：/称为…），不作为证据。"""
        nxt = text[vend:vend + 1]
        if not nxt:
            return True
        freq = self._get_jieba().dt.FREQ.get(verb + nxt)
        return not (freq and freq >= _SPEECH_VERB_BIGRAM_MIN)

    def _enum_chunk_ok(self, w: str) -> bool:
        """枚举块是否可作为人名证据：姓氏开头 + 非黑名单/常用词/地名/虚词尾
        + 机构/部门后缀否决（某县工厂/监察部 类职务机构枚举不是人名）
        + 词性否决（块内无 nr 词且含真实词典词 → 是普通词语，如 石化/涂装/党员）。"""
        if w[0] not in SINGLE_SURNAMES and w[:2] not in COMPOUND_SURNAMES:
            return False
        if w in NON_NAME_BLACKLIST or w in COMMON_WORDS or w in _PLACE_WORDS:
            return False
        if w[-1] in _FUNCTION_TAIL:
            return False
        if w.endswith(_ENUM_ORG_SUFFIXES):
            return False  # 某县工厂/示例丁工厂/监察部/客服部 等
        # posseg 否决（v1.3 约束：仅做否决，不做正向证据）
        from jieba import posseg
        words = posseg.lcut(w)
        if not any(f == "nr" for _, f in words):
            freq = self._get_jieba().dt.FREQ
            if any((freq.get(t) or 0) >= 20 for t, _ in words):
                return False  # 全非人名词 + 含真实词条（石化/涂装/党员/大学学历…）
        return True

    def _enum_split_chunks(self, text: str, m) -> tuple:
        """枚举段切块+坏块重切（LIST/PAIR 两段复制粘贴
        实现合并为公共函数，行为不变）。返回 (fixed, good)：
        fixed=[(a,b,w,ok)]，good=[(a,b)] 其中 ok 块。"""
        seg = m.group(0)
        base = m.start()
        parts, pos = [], 0
        for p in re.split(r"[、和及与]", seg):
            j = seg.find(p, pos)
            parts.append((base + j, base + j + len(p), p))
            pos = j + len(p)
            # 坏块（前缀吞字，如「股东为张三」被贪婪切为「东为张」+「三」）
        # 内重切出姓氏起始子块并恢复为好块
        fixed = []
        for a, b, w in parts:
            if not w:
                continue
            if self._enum_chunk_ok(w):
                fixed.append((a, b, w, True))
                continue
            for i in range(1, len(w) - 1):
                sub = w[i:]
                if 2 <= len(sub) <= 4 and sub[0] in SINGLE_SURNAMES                             and self._enum_chunk_ok(sub):
                    fixed.append((a + i, b, sub, True))
                    break
            else:
                fixed.append((a, b, w, False))
        good = [(a, b) for a, b, w, ok in fixed if ok]
        return fixed, good

    def _enum_evidence(self, text: str) -> set:
        """人名枚举列表证据（v1.6）：“甲、乙、丙、丁”式名单中的块位置集合。

        - 连续 ≥3 块的列表，且 ≥2 块姓氏开头且非地名/常用词 → 这些块全部采信；
        - 仅 2 块的短列表，需紧邻人名语境词（签字会计师姓名、联系人…）方采信。
        返回 {(start, end), …}，主循环中命中者按强上下文证据（score=3）放行。
        """
        spans: set = set()
        for m in _ENUM_LIST_RE.finditer(text):
            # 按分隔符切块（替代 CJK run 贪婪正则——「股东为张三」
            # 曾被切成「东为张三」吞掉首个人名；split 天然保住全部名单项）
            fixed, good = self._enum_split_chunks(text, m)
            if len(good) >= 2 and len(fixed) >= 3:
                spans.update(good)
        for m in _ENUM_PAIR_RE.finditer(text):
            # PAIR 短列表同样切块+坏块重切（公共函数）
            fixed, good = self._enum_split_chunks(text, m)
            if len(good) == len(fixed) and len(good) >= 2:
                prefix = text[max(0, m.start() - 14):m.start()]
                if any(h in prefix for h in _ENUM_HEAD_HINTS):
                    spans.update(good)
        return spans

    def _person_candidates(self, text: str, force_person: bool = False,
                           _merge_gap_spaces: bool = True) -> list:
        """人名：姓氏候选 + 上下文证据（前置职务/角色词 或 后缀称谓）双条件。

        实测教训：仅凭“姓氏 + 2~4 字”会在真实文档上大量误报（如制度文件中的
        “规章文件编号→章文件”“财务管理制度→管理制”“公司董事会→司董事”）。
        因此候选默认必须命中至少一条上下文证据才视为人名；补充通道：
        - person_loose 宽松档：姓氏之外的字全为常见名用字且不含高频词；
        - force_person 强制档：调用方（Excel 表头驱动的人名列）明确指定，
          仅保留黑名单等基础闸门，无上下文也视为完整人名。
        """
        best: dict = {}
        # v1.6 人名枚举列表证据（“实际控制人为（甲、乙、丙）”、股东/经办人名单）
        enum_spans = set() if force_person else self._enum_evidence(text)
        # 行首职务标签锚定（人名第三锚）——并入同一
        # 强证据集合：is_enum 豁免（边界伪词守卫/jieba 词边界否决）与名单
        # 枚举块同理（名单人名会被词典词跨界切开，如 长庆/建平 类切分）；
        # score=3 高置信放行，词条/构字/黑名单等闸门不豁免（不绕闸）。
        if not force_person:
            enum_spans |= _label_anchor_spans(text)
            # 竖排空格对齐名单版式广义通道——≥3 连行
            # 短 CJK 串+空格对齐且行尾无闭集职务词的名单版式（标签锚定通道不管辖的
            # 广义增量）。锚定 span 并入同一强证据集合（与标签锚定 span 全同时
            # 集合并集天然去重，不双生成）；检出行数计入观察计数（闸门加倍
            # 条款的降级观察模式数据面）。窗口只含 \n 连续行——原生 PDF 整页
            # 文本/多行连投可见；docx 逐段、OCR 无分隔拼接的喂入口径下行间
            # 窗口不可达（该面由行级通道管辖，见通道块注释）。
            _lay_spans, _lay_rows = _layout_list_spans(text)
            if _lay_rows and _merge_gap_spaces:
                self.stats_layout_list_rows += _lay_rows  # 镜像重扫不重复计数
            enum_spans |= _lay_spans
        # v1.7 闭环：表单字段行末块（“验收人：示例甲家居股份有限公司 某某”
        # ——字段与人名之间隔着公司全名，前缀窗口够不到）。取表单字段行内
        # 最后一个 2~4 字 CJK 块视为字段值（强证据）；行内其余长块是公司名/
        # 机构名，由公司管线处理。非姓氏开头块由主循环姓校验天然排除。
        field_value_spans: set = set()
        if not force_person:
            for fw in _FORM_FIELD_KEYS:
                fs = 0
                while True:
                    fi = text.find(fw, fs)
                    if fi < 0:
                        break
                    fs = fi + 1
                    fe = fi + len(fw)
                    if fe < len(text) and text[fe] in ":：":
                        fe += 1
                    line_end = text.find(chr(10), fe)
                    if line_end < 0:
                        line_end = min(len(text), fe + 80)
                    blocks = [(m.start(), m.end()) for m in
                              _CJK_RUN_RE.finditer(text, fe, line_end)
                              if 2 <= m.end() - m.start() <= 4]
                    if blocks:
                        field_value_spans.add(blocks[-1])
        # 预扫描“禁区”区间：职务关键词 + 高频双字词。候选起点落在区间内部时排除，
        # 避免“主管李工”命中“管李”（管为姓氏且恰好接住后缀称谓）、
        # “公司财务会计”命中“司财务”这类误报。
        reject_spans: list = []
        for kw in list(_KEYWORD_BEFORE) + list(_MID_WORD_BOUNDARIES):
            start = 0
            while True:
                i = text.find(kw, start)
                if i < 0:
                    break
                reject_spans.append((i, i + len(kw)))
                start = i + 1
        for run_m in _CJK_RUN_RE.finditer(text):
            s = run_m.group()
            base = run_m.start()
            n = len(s)
            for i in range(n):
                for length in (2, 3, 4):
                    if i + length > n:
                        break
                    w = s[i:i + length]
                    is_compound = w[:2] in COMPOUND_SURNAMES
                    if is_compound:
                        if length < 3:
                            continue
                    else:
                        if w[0] not in SINGLE_SURNAMES:
                            continue
                        if length == 4:
                            continue  # 单姓一般不超过 3 字（TODO: 少数民族姓名可扩展）
                    if w in NON_NAME_BLACKLIST:
                        continue
                    if "公司" in w or "集团" in w:
                        continue  # v1.7.2 对齐轮：人名候选含机构词必为公司边界误报（向公司/司集团类）
                    if w[-1] in _PERSON_BIZ_TAIL and w not in NON_NAME_WHITELIST_PERSON:
                        self._trace("reject", "person", w, "gate=biz_tail")
                        continue  # 尾字为业务字（单位/单号/应确/费用付/查新费类切词）
                    if w[-1] in _FUNCTION_TAIL:
                        self._trace("reject", "person", w, "gate=func_tail")
                        continue  # 末字为虚词：如“张三和”实为“张三”+连词，排除
                    cand_start = base + i
                    if any(k0 < cand_start < k1 for k0, k1 in reject_spans):
                        self._trace("reject", "person", w, "gate=keyword_zone")
                        continue
                    if any(cand_start < pe and ps < cand_start + length
                           for ps, pe in self._book_title_spans(text)):
                        self._trace("reject", "person", w, "gate=book_title")
                        continue  # 书名号内不识人名（如《会计法》）  # 候选起点嵌在关键词/高频词内部（如“主管”的“管”、“公司”的“司”）
                    # ---- 边界词守卫（兜底保留）：候选与前后相邻字构成常用词 → 是词的碎片 ----
                    # 枚举块豁免：块边界由分隔符结构确定（“某植平和”的“平和”是跨界伪词）
                    # v1.6.5：后邻字为接续动词首字（某晨光|复核 →“光复”伪词）不否决
                    prev_ch = text[cand_start - 1] if cand_start > 0 else ""
                    next_ch = text[cand_start + length] if cand_start + length < len(text) else ""
                    is_enum = (cand_start, cand_start + length) in enum_spans
                    _follow = text[cand_start + length:cand_start + length + 2] in _FOLLOW_VERBS
                    if not is_enum and (
                            (prev_ch and (prev_ch + w[0]) in COMMON_WORDS)
                            or (next_ch and (w[-1] + next_ch) in COMMON_WORDS
                                and not _follow)):
                        self._trace("reject", "person", w, "gate=boundary_word")
                        continue
                    # ---- jieba 词边界否决（v1.3 改造一，严格/宽松档；强制档豁免）----
                    # 候选与某词部分重叠（词内嵌、跨词切一半）→ 直接否决；
                    # 枚举块同样豁免（分词会把“某植平和某晨光”按词典词“平和”切开）
                    if not force_person and not is_enum \
                            and self._jieba_veto(text, cand_start, cand_start + length):
                        self._trace("reject", "person", w, "gate=jieba_boundary")
                        continue
                    # ---- 严格档证据打分 ----
                    score = 0
                    title2 = s[i + length:i + length + 2]
                    title1 = s[i + length:i + length + 1]
                    if title2 in _TITLE_AFTER2 and self._title_standalone(
                            text, cand_start + length, title2):
                        score += 3
                    if title1 in _TITLE_AFTER1 and self._title_standalone(
                            text, cand_start + length, title1):
                        score += 2
                    # v1.6.5：“王总/李工”式称呼的称谓在候选内部
                    # （候选本身=姓+称谓），称谓独立成义（总在/工，非总裁/工厂）
                    # 时视为称谓证据；和总|裁（总裁）仍被排除
                    if length == 2 and not is_compound and w[1] in _TITLE_AFTER1 \
                            and self._title_standalone(text, cand_start + 1, w[1]):
                        score = max(score, 2)
                    prefix = text[max(0, cand_start - 8):cand_start]
                    # 职务前缀须紧贴候选（顿号/逗号隔开的是“职务枚举”，不是名字，
                    # 如“负责人、示例乙事业部负责人”“非独立董事、某科技总经理”）
                    _pk = prefix.rstrip("：: 为系是 \t\n\r　")
                    if any(_pk.endswith(k) for k in _KEYWORD_BEFORE):
                        score += 2  # “法定代表人为某伟”：“为”剥离后命中“代表人”
                    if any(_pk.endswith(k) for k in _FORM_FIELD_KEYS):
                        score = max(score, 3)  # 表单字段后必是人名（姓名：某继发）
                    # 改造三：陈述动词 / 关系词 / “系”字句 → 高置信（对高危姓同样有效）
                    cand_end = cand_start + length
                    after = text[cand_end:cand_end + 4]
                    # 岗位后置（名字在前、岗位在后）——「某兵（批准人）」
                    # 「某建生-总裁」类：候选后紧邻（/－/- 且其后为岗位词 → 强证据
                    after2 = text[cand_end:cand_end + 6]
                    if after2.startswith(("（", "(")):
                        inner = after2[1:].split("）")[0].split(")")[0]
                        if inner and (inner in _KEYWORD_BEFORE or inner in _FORM_FIELD_KEYS
                                      or any(inner.endswith(k) for k in _KEYWORD_BEFORE)):
                            score = max(score, 3)
                    for sep in ("-—–",):
                        if after2.startswith(sep):
                            tail = after2[len(sep):]
                            if any(tail.startswith(j) for j in _TITLE_AFTER2)                                     or (tail[:1] and tail[:1] in _TITLE_AFTER1):
                                score = max(score, 2)
                            break
                    if after.startswith("简历"):
                        score = max(score, 3)  # 传记标题：“某勇简历：某勇，1970 年…”
                    for v in _STATEMENT_VERBS:
                        if after.startswith(v) and self._verb_is_speech(v, text, cand_end + len(v)):
                            score = max(score, 3)
                            break
                    if any(after.startswith(r) for r in _RELATION_WORDS):
                        score = max(score, 3)
                    if prefix.endswith("系") and any(
                            after.startswith(t) for t in _SYSTEM_TAILS):
                        score = max(score, 3)
                    # v1.6 枚举列表证据：候选恰为名单中的一个块 → 强上下文
                    if is_enum:
                        score = max(score, 3)
                    # v1.7 表单字段行末块 → 强证据（同 姓名：某继发 语义）
                    if (cand_start, cand_start + length) in field_value_spans:
                        score = max(score, 3)

                    high_risk = (w[0] in HIGH_RISK_SURNAMES) if not is_compound \
                        else (w[:2] in HIGH_RISK_SURNAMES)
                    # ---- v1.6.2 词条/构字否决（强制档豁免）----
                    # A'：候选是词典词条且词性非名字类（申请/施工/查询/应该/单号…）
                    #     → 无论证据多强都不是人名（李强nrfg/高山ns/白石nr 等放行）
                    # B ：弱证据（职务前缀）时，候选切分出的多字真实词条含非名字
                    #     用字（应按:照/和预:算/向公:司…）→ 是词组碎片而非人名。
                    #     强证据（枚举/称谓/陈述动词/关系词/简历）不适用，
                    #     保 某晨光(晨光)/某云福(白云)/某天宇(天宇) 等含词真名。
                    if not force_person:
                        if self._fragment_dict_veto(w):
                            self._trace("reject", "person", w, "gate=fragment_dict")
                            continue
                        given = w[2:] if is_compound else w[1:]
                        if score < 3 and self._fragment_given_veto(w):
                            self._trace("reject", "person", w, "gate=fragment_given")
                            continue
                        # 高危姓（和/应/章/单…）+ 弱证据：仍需名字形态校验；
                        # 总/工 是称谓用字（李工/王总 形），额外要求候选后邻字
                        # 不与末字构成词条（和总|裁→总裁 否决；李工|，放行）
                        if high_risk and score < 3:
                            if not given or any(ch not in GIVEN_CHARS and ch not in "总工"
                                                 for ch in given):
                                self._trace("reject", "person", w, "gate=highrisk_given")
                                continue
                            nxt1 = text[cand_start + length:cand_start + length + 1]
                            if nxt1 and _cjk(nxt1) \
                                    and ((self._get_jieba().dt.FREQ.get(w[-1] + nxt1) or 0) >= 100) \
                                    and text[cand_start + length:cand_start + length + 2] not in _FOLLOW_VERBS:
                                self._trace("reject", "person", w, "gate=highrisk_pseudo")
                                continue  # 光复/腾出 类伪词；复核/出席 类接续动词例外
                    if score > 0 or force_person:
                        # 严格档 / 强制档：放行，高置信
                        conf = PERSON_CONF_HIGH
                    else:
                        given = w[2:] if is_compound else w[1:]
                        if high_risk:
                            # 高危姓：宽松档禁用；交叉放行需条件全满足（中置信）：
                            # (a) 通过词边界校验（外层已过滤部分重叠）
                            # (b) 姓外字全命中名用字表
                            # (c) 前后邻字不构成常用词
                            # (d) 候选恰为完整词条且词性非人名 → 否决（如“高山流水”）
                            if not self.opt.person_loose:
                                self._trace("reject", "person", w, "gate=hr_loose_off")
                                continue
                            if not given or any(ch not in GIVEN_CHARS for ch in given):
                                self._trace("reject", "person", w, "gate=hr_cross_given")
                                continue
                            if (prev_ch and (prev_ch + w[0]) in COMMON_WORDS) \
                                    or (next_ch and (w[-1] + next_ch) in COMMON_WORDS
                                        and text[cand_start + length:cand_start + length + 2]
                                        not in _FOLLOW_VERBS):
                                self._trace("reject", "person", w, "gate=hr_cross_boundary")
                                continue
                            if length >= 3 and w[1:] in COMMON_WORDS:
                                self._trace("reject", "person", w, "gate=hr_cross_family")
                                continue  # 家族闸门：如"和建立"（建立为常用词）
                            if length == 2 and (_cjk(prev_ch) or _cjk(next_ch)):
                                self._trace("reject", "person", w, "gate=hr_cross_adjacent")
                                continue  # 汉字邻接：疑为词碎片；顿号/括号/换行边界放行
                            if self._is_common_dict_word(text, cand_start, cand_start + length):
                                self._trace("reject", "person", w, "gate=hr_cross_dictword")
                                continue
                            conf = PERSON_CONF_MID
                        else:
                            # 低危姓宽松档（原逻辑 + jieba 否决 + 词条否决）
                            if not self.opt.person_loose:
                                self._trace("reject", "person", w, "gate=loose_off")
                                continue
                            if not given or any(ch not in GIVEN_CHARS for ch in given):
                                self._trace("reject", "person", w, "gate=loose_given")
                                continue
                            if (w in COMMON_WORDS or w[:2] in COMMON_WORDS
                                    or (length >= 3 and w[1:] in COMMON_WORDS)):
                                self._trace("reject", "person", w, "gate=loose_lexicon")
                                continue
                            if length == 2 and (_cjk(prev_ch) or _cjk(next_ch)):
                                self._trace("reject", "person", w, "gate=loose_adjacent")
                                continue  # v1.6：仅汉字邻接视为碎片；标点/换行边界放行
                            if self._is_common_dict_word(text, cand_start, cand_start + length):
                                self._trace("reject", "person", w, "gate=loose_dictword")
                                continue  # 候选是真实词条（词性非人名）→ 否决
                            conf = (PERSON_CONF_MID
                                    if self._is_nr_word(text, cand_start, cand_start + length)
                                    else PERSON_CONF_LOW)
                    # TODO: 人名置信度打分——结合误报样本集回填持续调优
                    pref = 1 if ((length == 4) if is_compound else (length == 3)) else 0
                    cand = _Cand(cand_start, cand_start + length, "person", w,
                                 self._default_replacement("person", w), score, conf)
                    prev = best.get(cand_start)
                    if prev is None or (cand.score, pref) > prev[1]:
                        best[cand_start] = (cand, (cand.score, pref))
        cands = [cand for cand, _ in best.values()]
        # 排版空格归一重试（主循环之后；_merge_gap_spaces=False
        # 为镜像重扫自身的递归入口，杜绝二阶递归）
        if _merge_gap_spaces:
            cands = self._merge_gap_space_candidates(text, force_person, best)
        return cands

    def _merge_gap_space_candidates(self, text: str, force_person: bool,
                                    best: dict) -> list:
        """双字名内嵌排版空格的候选归一重试。

        做法：找出文本中全部「合规接缝」（_person_gap_spans 形态闸 + 总跨度
        ≤4），构造接缝全部闭合的镜像文本，对镜像**整体重跑**
        _person_candidates 完整流水线——枚举/证据打分/严格档/宽松档/jieba
        否决/词条构字否决与主通道逐字节同源，合并串不绕过任何闸门；随后仅
        回收「跨越接缝」的候选（其余与主通道产物重复，弃用以保语义单一），
        并映射回原文本坐标（区间含被剔除的空格，替换文本按合并串生成，
        如「唐某」→「唐*」）。同起点冲突与主循环同规则择优 (score, pref)。
        """
        gspans = _person_gap_spans(text)
        if not gspans:
            return [cand for cand, _ in best.values()]
        # 镜像文本 + 坐标映射（镜像下标 → 原文下标）：只剔除接缝内的空格
        # 字符，两侧段首/段尾汉字保留（接缝=空格位闭合，不是整段删除）
        mirror_chars: list = []
        pos_map: list = []
        gi = 0
        for idx, ch in enumerate(text):
            if gi < len(gspans) and gspans[gi][0] <= idx < gspans[gi][1]:
                if idx == gspans[gi][1] - 1:
                    gi += 1  # 走出当前接缝（gspans 升序、至多共享边界字）
                if ch in _GAP_SPACE_CHARS:
                    continue
            mirror_chars.append(ch)
            pos_map.append(idx)
        if len(mirror_chars) == len(text):
            return [cand for cand, _ in best.values()]  # 全部接缝为空长（理论不可达）；防御性保底
        mirror = "".join(mirror_chars)
        mirror_cands = self._person_candidates(
            mirror, force_person, _merge_gap_spaces=False)
        for c in mirror_cands:
            o_start = pos_map[c.start]
            o_end = pos_map[c.end - 1] + 1
            # 仅保留跨越接缝的候选（区间与某接缝相交；纯段内候选主通道已有）
            if not any(o_start < ge and gs < o_end for gs, ge in gspans):
                continue
            orig = text[o_start:o_end]
            cand = _Cand(o_start, o_end, "person", orig, c.replacement,
                         c.score, c.confidence)
            # 同起点择优与主循环同规则（镜像候选长度按合并串计）
            m_len = c.end - c.start
            is_comp = c.text[:2] in COMPOUND_SURNAMES
            pref = 1 if ((m_len == 4) if is_comp else (m_len == 3)) else 0
            prev = best.get(o_start)
            if prev is None or (cand.score, pref) > prev[1]:
                best[o_start] = (cand, (cand.score, pref))
        return [cand for cand, _ in best.values()]

    def _amount_candidates(self, text: str) -> list:
        out = []
        for m in AMOUNT_RE.finditer(text):
            s = m.group()
            if self._amount_ok(s):
                out.append(_Cand(m.start(), m.end(), "amount", s, self._default_replacement("amount", s)))
        # v1.7.3：金额类标签引导的裸数字（「退款金额\n2223」）——常规 AMOUNT_RE
        # 对无单位纯数字不认，此处按标签紧邻（≤12 空白字符，允许跨行）认定；
        # 仅应用阈值不过 _amount_ok（其无单位闸会误杀本通道）
        picked = [(c.start, c.end) for c in out]
        for m in AMOUNT_LABELED_RE.finditer(text):
            a, b, s = m.start(1), m.end(1), m.group(1)
            if any(a < e and s0 < b for s0, e in picked):
                continue
            # 年份否定（镜像 pdf 侧 OCR 金额列口径）——
            # 捕获类 \d{3,} 会吞「余额\n2023」「合计：2024」四位年份与
            # YYYYMMDD 八位日期；本通道有意绕过 _amount_ok（无单位闸），
            # 此前对年份完全不设防（文本层独立缺口：docx/xlsx/pptx/PDF
            # 原生页四链路共用本正则）。八位带月/日合法性校验（
            # 「合计 20500000」类 8 位真金额不误拒）。
            if re.fullmatch(r"(?:19|20)\d\d", s) or re.fullmatch(
                    r"(?:19|20)\d\d(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])", s):
                self._trace("reject", "amount", s, "gate=labeled_year")
                continue
            value = parse_amount(s)
            if value is None or abs(value) <= self.opt.amount_threshold:
                self._trace("reject", "amount", s, "gate=labeled_threshold")
                continue
            out.append(_Cand(a, b, "amount", s, self._default_replacement("amount", s)))
            picked.append((a, b))
        return out

    def _amount_ok(self, s: str) -> bool:
        """金额有效性过滤：排除日期/版本号/编号等误判，并应用阈值。"""
        # v2.0.2：千档入 has_unit（「2千元」本带元字必真，「￥2千」靠此）；
        # 解析走千档感知包装（utils.parse_amount 不识千，直呼必 None）。
        has_unit = ("元" in s) or ("￥" in s) or ("¥" in s)             or ("万" in s) or ("亿" in s) or ("千" in s)  # 万/亿本身即货币单位（大于 10 万/额度 1 亿）；v2.0.2：+千档
        value = _parse_amount_qian(s)
        if value is None:
            self._trace("reject", "amount", s, "gate=amount_parse_fail")
            return False
        if not has_unit:
            if "," not in s:
                # 无货币标记：要求小数且整数部分 >= 3 位，避免把 v1.2 之类误判为金额
                if "." not in s:
                    self._trace("reject", "amount", s, "gate=amount_nounit_nodot")
                    return False
                int_part = s.split(".", 1)[0]
                if len(int_part.lstrip("0")) < 3:
                    self._trace("reject", "amount", s, "gate=amount_nounit_smallint")
                    return False
                if len(int_part) == 4 and 1900.0 <= value < 2100.0:
                    self._trace("reject", "amount", s, "gate=amount_year_form")
                    return False  # 疑似 2026.09 这类日期/版本号
        if abs(value) > self.opt.amount_threshold:
            return True  # 保持 > 比较（与原单 return 严格同义，NaN 不可达亦不翻转）
        self._trace("reject", "amount", s, "gate=amount_threshold")
        return False

    # ---- 地址脱敏（v1.6）--------------------------------------------------

    def _address_candidates(self, text: str) -> list:
        """地址候选：行政区划 + 街巷/门牌/楼宇结构，或“地址：”标签引导。"""
        out: list = []
        seen: set = set()
        for rx in (ADDRESS_RE, ADDRESS_LABELED_RE):
            for m in rx.finditer(text):
                a, b, s = m.start(), m.end(), m.group()
                if rx is ADDRESS_LABELED_RE:
                    lm = re.match(_ADDR_LABEL, s)
                    if lm is None or lm.end() >= len(s.rstrip()):
                        continue  # 只有标签没有地址实体
                    a += lm.end()
                    s = s[lm.end():]
                else:
                    # 左缘引导字（“注册地址：为深圳市…”的“为”）不属于地址本体
                    while s and s[0] in "为是在于和与及或系" and len(s) - 1 >= 5:
                        a += 1
                        s = s[1:]
                if (a, b) in seen or not self._address_ok(text, s, a, b,
                                                          labeled=rx is ADDRESS_LABELED_RE):
                    continue
                seen.add((a, b))
                out.append(_Cand(a, b, "address", text[a:b],
                                 self._address_replacement(text[a:b])))
        return out

    def _address_ok(self, text: str, s: str, a: int, b: int,
                    labeled: bool = False) -> bool:
        """地址有效性：≥2 个区划块，或 ≥1 区划块 + ≥1 个街巷/门牌细节；
        标签引导式（“地址：…”）无区划时需 ≥2 个细节；书名号内、紧邻机构词
        （实为机构名一部分）时放弃。"""
        if len(s) < 5:
            return False
        # 泛指地域/城市类别词放行（纠偏白名单——「一类城市」「二类城市」
        # 等类别词被当地址实体误遮，表头实例）。用包含式匹配：
        # OCR 拼接形态「一类城市二类城市三类城市」与嵌句形态「除一类城市及二类
        # 城市以外的其他城市」一并否决（fullmatch 挡不住拼接）。
        if re.search(r"[一二三四五六七八九十\d]+\s*类?\s*城市", s):
            return False
        if any(ps < b and a < pe for ps, pe in self._book_title_spans(text)):
            return False
        if _ADDR_ORG_CONT_RE.match(text, b):
            return False
        admins = re.findall(_ADDR_ADMIN, s)
        rest = re.sub(_ADDR_ADMIN, "", s)
        details = len(re.findall(
            r"号|大道|大街|路|街|巷|道|大厦|大楼|广场|园区|公寓|小区|花园|苑|城|"
            r"座|栋|幢|单元|层|楼|室", rest))
        if labeled:
            return bool(admins) or details >= 2
        return len(admins) >= 2 or (bool(admins) and details >= 1)

    @staticmethod
    def _address_replacement(s: str) -> str:
        """结构保持替换：前缀遮蔽为 ×，区划/街巷/楼层后缀保留。"""
        parts: list = []
        for um in _ADDR_UNIT_RE.finditer(s):
            u = um.group()
            if u[0].isalnum() and u[0].isascii():
                parts.append("×")
                continue
            for suf in _ADDR_SUFFIXES:
                if u.endswith(suf):
                    prefix = u[:len(u) - len(suf)]
                    parts.append("×" * min(len(prefix), 2) + suf if prefix else suf)
                    break
            else:
                parts.append("××")
        return "".join(parts)


    def _extra_candidates(self, text: str) -> list:
        out = []
        for name, rx, vfn, rfn in self._extra_rules:
            for m in rx.finditer(text):
                s = m.group()
                if vfn is not None and not vfn(s):
                    continue
                out.append(_Cand(m.start(), m.end(), name, s, rfn(s) if rfn else "***"))
        return out

    # ---- 替换文本生成 ---------------------------------------------------

    def _default_replacement(self, rule: str, s: str) -> str:
        """各规则默认替换文本（部分遮罩，兼顾可读性与脱敏强度）。

        TODO: 可在此按业务需求调整遮蔽粒度（如身份证保留前后 4 位等）。
        """
        if rule == "id_card":
            return s[:6] + "*" * 8 + s[-4:]
        if rule == "phone":
            return s[:3] + "****" + s[-4:]
        if rule == "email":
            local, _, domain = s.partition("@")
            dl = domain.lower()
            if any(k in dl for k in self._brand_domain_hints):
                return "***"  # 品牌域名整址遮盖（域名本身可反推公司身份）
            return (local[:1] if local else "*") + "***@" + domain
        if rule == "uscc":
            return s[:6] + "*" * 12
        if rule == "account":
            # 银行账号：保留前 4 后 4（与身份证部分遮蔽强度一致；源文档自身
            # 打码惯例为 621225360*********，本样式可辨识度更低）
            return s[:4] + "*" * max(4, len(s) - 8) + s[-4:]
        if rule == "person":
            if s[:2] in COMPOUND_SURNAMES:
                return s[:2] + "*" * (len(s) - 2)
            return s[:1] + "*" * (len(s) - 1)
        if rule == "amount":
            return self._replace_amount(s)
        return "***"

    def _replace_amount(self, s: str) -> str:
        """金额替换：部分遮罩 > 四舍五入到万位 > 整体遮罩。"""
        if self.opt.amount_partial:
            return partial_mask_amount(s)
        if self.opt.amount_mode == "scale" and self.amount_scale_K:
            # 缩放脱敏：显示值 = 原值 × K（K 为每批次随机系数，公式写入映射表）
            # v2.0.2：千档感知解析；千档原文按元值渲染（数值等价，
            # 量纲字尾统一为元——缩放本身即改写显示值，无原文残留面）
            value = _parse_amount_qian(s)
            if value is not None:
                scaled = value * self.amount_scale_K
                if "万元" in s:
                    return f"{scaled / 10000:,.2f}万元"
                if s.startswith(("￥", "¥")):
                    return s[0] + f"{scaled:,.2f}"
                if "元" in s:
                    return f"{scaled:,.2f}元"
                return f"{scaled:,.2f}"
            return "***"
        if self.opt.amount_mode == "round_wan":
            value = _parse_amount_qian(s)  # v2.0.2：千档感知解析
            if value is not None and abs(value) >= 10000:
                return f"{round(value / 10000)}万元"
            return "***"  # 不足 1 万按整体遮罩，避免四舍五入失真（TODO: 可调策略）
        return "***"

    def mask_numeric(self, value) -> object:
        """数值单元格金额脱敏（Excel 专项）：返回 None 表示不处理。

        数值单元格与文本单元格在此分流；返回字符串会让单元格变为文本显示。
        scale 模式返回数值（保留数字类型，公式重算后勾稽关系同步缩放）。
        TODO: 可结合 number_format 保留“万元”等显示格式。
        """
        if not self.opt.mask_amount or self._words_only:
            # v2.1.8 words_only：数值格金额通道随模式停用
            return None
        if abs(float(value)) <= self.opt.amount_threshold:
            return None
        if self.opt.amount_mode == "scale" and self.amount_scale_K:
            return round(float(value) * self.amount_scale_K, 2)
        if self.opt.amount_mode == "round_wan":
            if abs(float(value)) >= 10000:
                return f"{round(float(value) / 10000)}万元"
            return "***"
        if self.opt.amount_partial:
            return partial_mask_amount(str(value))
        return "***"
