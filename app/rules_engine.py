# 复合量词档解析（千万/百亿/十亿）——「￥2千万」此前被
# 单字类截成「￥2千」（量级误读 2000 vs 2×10⁷）、裸「2千万/2千万元」整笔
# 零命中；AMOUNT_RE 三支已换复合 alternation，解析在此等价换算（千位分隔
# 符语境无汉字量词天然不进；_amount_ok/_replace_amount 两消费点共用）。
# 位置说明同上：锚后放置，保 575 前行号零位移。
_COMPOUND_UNIT_RE = re.compile(
    r"^\s*(?:(?:￥|¥)\s*)?(\d[\d,]*(?:\.\d{1,2})?)"
    r"\s*(千万|百亿|十亿)\s*(?:元)?\s*$")
_COMPOUND_UNIT_MULT = {"千万": 10000000.0, "十亿": 1000000000.0,
                       "百亿": 10000000000.0}


def _parse_amount_qian(s: str):
    """金额解析（千档/复合量词感知）：「2千元/￥2千」→ ×1000；
    「2千万/￥2千万元/3百亿」→ 复合档换算；其余形态透传
    _parse_amount_qian_base（含 utils.parse_amount 的 None 语义）。"""
    m = _COMPOUND_UNIT_RE.match(s)
    if m is not None:
        return float(m.group(1).replace(",", "")) * _COMPOUND_UNIT_MULT[m.group(2)]
    return _parse_amount_qian_base(s)
