    def _get_jieba(self):
        """惰性加载 jieba；缓存文件指到程序数据目录 _cache（v1.9.2a 起不落
        系统 TEMP——源码态=项目根/_cache，冻结态=exe 同目录/_cache，与
        config.json/brands.json 同惯例；只读环境兜底禁用缓存）。"""
        if self._jieba is None:
            import os
            import jieba
            cache_dir = os.path.join(str(program_data_dir()), "_cache")
            try:
                os.makedirs(cache_dir, exist_ok=True)
                jieba.dt.cache_file = os.path.join(cache_dir, "jieba.cache")
            except OSError:
                jieba.dt.cache_file = None  # 禁用缓存（只读环境兜底）
            self._jieba = jieba
        return self._jieba

    def _cache_put(self, cache: dict, key, value) -> None:
        """无界缓存封顶：被缓存的计算均为 text 纯函数，
        整清后重算同值——零行为差，仅防跨整批所有文本块的内存无界增长。
        不变量前提：jieba/posseg 词典在进程生命周期内
        不可变（全库无 add_word/load_userdict 调用）；若未来引入运行期
        改词典，整清重算将与旧缓存不同，须改有界 LRU。"""
        if len(cache) >= 8192:
            cache.clear()
        cache[key] = value

    def _segment(self, text: str) -> list:
        """jieba 分词（带位置），按文本缓存，避免候选级重复分词。"""
        key = hash(text)
        words = self._seg_cache.get(key)
        if words is None:
            jieba = self._get_jieba()
            words = [(w, s, e) for w, s, e in jieba.tokenize(text, mode="default")]
            self._cache_put(self._seg_cache, key, words)
        return words

    def _pos_tags(self, text: str) -> dict:
        """jieba 词性标注（惰性）：词 -> 词性。"""
        key = hash(text)
        tags = self._pos_cache.get(key)
        if tags is None:
            from jieba import posseg
            tags = {w: flag for w, flag in posseg.lcut(text)}
            self._cache_put(self._pos_cache, key, tags)
        return tags

    def _jieba_veto(self, text: str, start: int, end: int) -> bool:
        """词边界否决：候选与【真实词典词】部分重叠（词被切了一半）→ 否决。

        候选恰好等于一个完整词、或由完整词首尾相接拼成时，不否决；
        HMM 对词典外文本的粘连切分（如“系文强”）不构成否决依据。
        v1.6.5：候选后紧邻“复核/审核/出席”等接续动词（主谓句式
        “某晨光复核”）时不否决——此时跨界词（光复）是伪词。
        """
        follow = text[end:end + 2] in _FOLLOW_VERBS
        for w, a, b in self._segment(text):
            if a >= end:
                break  # O(n²) 早退：token 起点升序，
                # a>=end 后条件 a<end 恒假；纯布尔消费零行为差
            if a < end and start < b and not (start <= a and b <= end):
                if follow:
                    continue
                if self._get_jieba().dt.FREQ.get(w):
                    return True  # 真实词典词被候选切了一半
        return False

    def _is_common_dict_word(self, text: str, start: int, end: int) -> bool:
        """候选恰为一个完整分词片段，且是【词典常用词条】→ 真实常用词，非未登录人名。

        判定（确定性，不依赖 HMM 词性噪声）：
        - 词典频次 ≥ 100 → 常用词（高峰/田园/花岗岩/马路…）；
        - 20 ≤ 频次 < 100 且词性非 nr → 常用词；
        - 低频（<20）或词典外 → 可能是人名，放行。
        """
        for w, a, b in self._segment(text):
            if a > start:
                break  # O(n²) 早退：起点升序越过 start
                # 后不可能再命中 a==start；纯布尔消费零行为差
            if a == start and b == end:
                jieba = self._get_jieba()
                freq = jieba.dt.FREQ.get(w)
                if freq is None:
                    return False  # 词典外（HMM 未登录组合）：可能是人名
                if freq >= 100:
                    return True  # 高频词条：常用词
                if freq >= 20:
                    from jieba import posseg
                    tag = posseg.dt.word_tag_tab.get(w)
                    if bool(tag) and tag != "nr":
                        return True  # 中低频但词性非人名：常用词
                return False  # 低频/未标注：可能是人名，放行

    def _is_nr_word(self, text: str, start: int, end: int) -> bool:
        """候选是否为 jieba 标注为 nr（人名）的完整词。"""
        for w, a, b in self._segment(text):
            if a > start:
                break  # O(n²) 早退：token 起点升序，
                # 越过 start 后不可能再命中 a==start；纯布尔消费零行为差
            if a == start and b == end:
                return self._pos_tags(text).get(w, "") == "nr"
        return False

    def _trace(self, kind: str, cat: str, word, evidence: str = "",
               conf: str = "") -> None:
        """决策留痕旁路：只追加元组，不参与任何判定（写盘侧再格式化）。

        kind=accept/reject；cat=rule 名或 register 等通道名；evidence=
        「gate=闸名;特征=值」紧凑串。词面与映射表同级敏感，仅落本地
        决策留痕_*.csv，不入库不外发。整体包异常=结构性保证纯追加
        （任何插桩缺陷不得波及遮蔽判定）。
        """
        try:
            if not self._trace_on or not word:
                return
            if len(self._decision_trace) >= 200000:
                self._trace_dropped += 1
                return
            w = word if isinstance(word, str) else str(word)
            self._decision_trace.append(
                (self._trace_file, kind, cat, w[:60], evidence[:120], conf))
        except Exception:
            pass

    def get_person_confidence(self, original: str) -> str:
        """查询某人名原文的最高置信度（映射表 CSV 输出用）；非人名返回空串。"""
        return self._person_conf.get(original, "")

    def get_confidence(self, rule: str, original: str) -> str:
        """查询某规则下原文的置信度（person/company 支持，其余返回空串）。"""
        if rule == "person":
            return self._person_conf.get(original, "")
        if rule == "company":
            return self._company_conf.get(original, "")
        return ""

    def register_confidence(self, rule: str, original: str, confidence) -> None:
        """注册实体置信度（v1.9.4 冻结重放轮回注用）。

        与 find_spans 检测路径同一取高准则（_CONF_RANK，同 :1305/:1322 式）；
        非 person/company 规则或空置信度忽略——冻结轮无检测，置信度只能来自
        plan 携带的首轮快照，缺失时汇总表该行置信度列为空（与首轮一致）。
        """
        if not confidence or rule not in ("person", "company"):
            return
        conf_map = self._person_conf if rule == "person" else self._company_conf
        prev = conf_map.get(original, "")
        if _CONF_RANK.get(confidence, 0) > _CONF_RANK.get(prev, -1):
            conf_map[original] = confidence

    def filename_replacement_pairs(self) -> list:
        """文件名脱敏用：已知实体的 (原文, 替换为) 列表，按原文长度降序。

        在【内容处理完成之后】调用——此时公司别名/简称/人名置信度均已登记，
        文件名按已知实体精确替换，天然正确处理双段文件名、无后缀简称。
        包含：对照表映射 + 自定义敏感词 + 公司别名 + 公司简称 + 人名。
        """
        pairs: list = []
        for orig, repl in self._mapping.items():
            pairs.append((orig, repl))
        for orig in self._word_keys:
            pairs.append((orig, self._custom_replacements.get(orig, "***")))
        for orig, repl in self._company_alias.items():
            pairs.append((orig, repl))
        for orig, repl in self._short_names.items():
            pairs.append((orig, repl))
        for orig in self._person_conf:
            pairs.append((orig, self._default_replacement("person", orig)))
        pairs.sort(key=lambda pr: len(pr[0]), reverse=True)
        return pairs

