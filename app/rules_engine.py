def _derive_brand(name: str, alias: str = "") -> tuple:
    """从公司全名派生品牌词：返回 (品牌或 None, 品牌替换文本)。

    示例甲家居股份有限公司 → (示例甲, ABC)；剥离公司后缀与一个通用行业
    尾词，品牌须 2~4 字且非常用词/地名/黑名单。
    """
    base = None
    for suf in sorted(_STRONG_SUFFIXES | _WEAK_SUFFIXES, key=len, reverse=True):
        if name.endswith(suf) and len(name) - len(suf) >= 2:
            base = name[:-len(suf)]
            break
    if base is None:
        return None, ""
    for g in _BRAND_GENERIC_TAILS:
        if base.endswith(g) and len(base) - len(g) >= 2:
            base = base[:len(base) - len(g)]
            break
    if not (2 <= len(base) <= 4):
        return None, ""
    if base in COMMON_WORDS or base in NON_NAME_BLACKLIST or base in _PLACE_WORDS:
        return None, ""
    brand_repl = alias
    if alias:
        for suf in sorted(_STRONG_SUFFIXES | _WEAK_SUFFIXES, key=len, reverse=True):
            if alias.endswith(suf) and len(alias) - len(suf) >= 1:
                brand_repl = alias[:-len(suf)]
                break
    return base, brand_repl


